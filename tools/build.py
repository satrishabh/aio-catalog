#!/usr/bin/env python3
"""Builds the artifacts AIO consumes from catalog/**.yaml:

  dist/catalog.yaml                  every entry in one file; AIO reads it (CONNECTORS_REPO + CONNECTORS_REVISION).
                                     A binding's manifests file is inlined as binding.manifestsText.
  deploy/connectors-project.yaml     the Argo CD AppProject "connectors": only this repo, the managed entries' chart
                                     repositories and their namespaces are allowed (the install guardrail)

  python tools/build.py           write both
  python tools/build.py --check   fail if they are out of date (CI)
"""
import glob
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_URL = os.environ.get("CATALOG_REPO_URL", "https://github.com/satrishabh/aio-catalog.git")
# Namespaces an entry writes into besides its own: kube-green's SleepInfo extras (dev, staging); the
# kube-prometheus-stack chart adds scrape Services for cluster DNS / kubelet in kube-system. Never prod.
EXTRA_NAMESPACES = {"kube-green": ["dev", "staging"], "prometheus": ["kube-system"],
                    "spark-operator": ["dev", "staging"], "flink-operator": ["dev", "staging"]}
HEADER = "# GENERATED by tools/build.py from catalog/**.yaml - do not edit by hand.\n"


def load():
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, "catalog", "**", "*.yaml"), recursive=True)):
        e = yaml.safe_load(open(path, encoding="utf-8"))
        b = e.get("binding")
        if b and b.get("manifests"):
            # The platform reads only dist/catalog.yaml: inline the binding's manifest template (still unsubstituted)
            with open(os.path.join(ROOT, b["manifests"]), encoding="utf-8") as f:
                b["manifestsText"] = f.read()
        out.append(e)
    order = {"core": 0, "managed": 1, "planned": 2}
    return sorted(out, key=lambda e: (order[e["kind"]], e["category"], e["id"]))


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper, value):
    # multi-line text (binding.manifestsText) as a literal block, so dist/catalog.yaml stays readable
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def catalog_text(entries):
    return HEADER + yaml.dump({"connectors": entries}, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110)


def project_text(entries):
    managed = [e for e in entries if e["kind"] == "managed"]
    repos = [REPO_URL] + sorted({e["chartRepo"] for e in managed})
    namespaces = sorted({e["namespace"] for e in managed}
                        | {ns for e in managed for ns in EXTRA_NAMESPACES.get(e["id"], [])})
    project = {
        "apiVersion": "argoproj.io/v1alpha1",
        "kind": "AppProject",
        "metadata": {"name": "connectors", "namespace": "argocd"},
        "spec": {
            "description": "Open-source connectors managed from the AIO portal (generated from aio-catalog)",
            "sourceRepos": repos,
            "destinations": [{"server": "https://kubernetes.default.svc", "namespace": ns} for ns in namespaces],
            # Operators ship CRDs, ClusterRoles and admission webhooks
            "clusterResourceWhitelist": [{"group": "*", "kind": "*"}],
            "namespaceResourceWhitelist": [{"group": "*", "kind": "*"}],
        },
    }
    return HEADER + "# Apply: kubectl apply -f deploy/connectors-project.yaml\n" + yaml.safe_dump(project, sort_keys=False)


def main():
    entries = load()
    outputs = {os.path.join(ROOT, "dist", "catalog.yaml"): catalog_text(entries),
               os.path.join(ROOT, "deploy", "connectors-project.yaml"): project_text(entries)}
    stale = []
    for path, text in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != text:
            stale.append(os.path.relpath(path, ROOT))
            if "--check" not in sys.argv:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if "--check" in sys.argv and stale:
        print("out of date (run python tools/build.py):", ", ".join(stale))
        sys.exit(1)
    print("built" if stale else "up to date", len(entries), "entries")


if __name__ == "__main__":
    main()
